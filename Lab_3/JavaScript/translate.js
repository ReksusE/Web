function getTranslate(lang) {
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.dataset.i18n;
    if (i18Obj[lang]?.[key]) {
      if (!el.dataset.i18nOriginal) {
        el.dataset.i18nOriginal = el.textContent.trim();
      }
      el.textContent = i18Obj[lang][key];
    }
  });
  
  document.querySelectorAll('input[data-i18n-placeholder], textarea[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (i18Obj[lang]?.[key]) {
      el.placeholder = i18Obj[lang][key];
    }
  });
  
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.dataset.i18nTitle;
    if (i18Obj[lang]?.[key]) {
      el.title = i18Obj[lang][key];
    }
  });
}

// === ПЕРЕКЛЮЧЕНИЕ ЯЗЫКА ===
function switchLanguage(lang) {
  localStorage.setItem('coursely_lang', lang);
  getTranslate(lang);
  document.querySelectorAll('.lang-switcher button').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
  document.documentElement.setAttribute('lang', lang);
}

// === ИНИЦИАЛИЗАЦИЯ ===
document.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem('coursely_lang') || 'ru';
  switchLanguage(savedLang);
  
  document.querySelectorAll('.lang-switcher button').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      switchLanguage(btn.dataset.lang);
    });
  });
});